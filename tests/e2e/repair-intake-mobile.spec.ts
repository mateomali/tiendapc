import { expect, test } from '@playwright/test';

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });

test('mobile intake removes failures and preserves the device', async ({ page }) => {
    await page.goto('/consulta');
    await page.locator('input[name=password]').fill(process.env.REPAIR_TECH_PASSWORD ?? 'Reypablo');
    await page.getByRole('button', { name: 'Ingresar', exact: true }).click();
    await page.goto('/ingreso');
    await page.getByLabel(/Nombre del cliente/).fill('Prueba sin guardar');
    await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
    await page.locator('select').filter({ has: page.locator('option', { hasText: 'Celulares' }) }).selectOption('1');
    const brand = page.getByRole('combobox', { name: 'Marca', exact: true });
    await brand.tap();
    await page.getByRole('option', { name: 'SAMSUNG', exact: true }).tap();
    await expect(brand).toHaveAttribute('aria-expanded', 'false');
    await page.getByPlaceholder('Ej: Samsung A54').fill('Samsung A54');
    const services = page.locator('select').filter({ has: page.locator('option', { hasText: 'Elegir falla o servicio frecuente...' }) });
    const descriptions = page.getByRole('textbox', { name: 'Detalle de la falla', exact: true });
    await expect(descriptions).toHaveCount(0);
    await expect(services.locator('option').last()).toHaveText('Otro servicio');
    await services.selectOption({ label: 'Desbloqueo' });
    await expect(descriptions).toHaveValue('Desbloqueo de equipo');
    await page.getByRole('button', { name: 'Quitar falla 1', exact: true }).tap();
    await expect(descriptions).toHaveCount(0);
    await expect(page.getByPlaceholder('Ej: Samsung A54')).toHaveValue('Samsung A54');
    await services.selectOption({ label: 'Desbloqueo' });
    await services.selectOption({ label: 'Cambio de bateria' });
    await expect(descriptions).toHaveCount(2);
    await page.getByRole('button', { name: 'Quitar falla 1', exact: true }).tap();
    await expect(descriptions).toHaveCount(1);
    await expect(descriptions).toHaveValue('Cambio de bateria');
    await expect(brand).toContainText('SAMSUNG');
    await expect(page.getByPlaceholder('Ej: Samsung A54')).toHaveValue('Samsung A54');
    await services.selectOption({ label: 'Desbloqueo' });
    await page.getByRole('button', { name: 'Quitar falla 2', exact: true }).tap();
    await expect(descriptions).toHaveCount(1);
    await expect(descriptions).toHaveValue('Cambio de bateria');
    const trash = await page.getByRole('button', { name: 'Quitar falla 1', exact: true }).boundingBox();
    expect(trash?.width).toBeGreaterThanOrEqual(44);
    expect(trash?.height).toBeGreaterThanOrEqual(44);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    const descriptionBox = await descriptions.boundingBox();
    const amountBox = await page.getByRole('textbox', { name: 'Monto', exact: true }).boundingBox();
    expect(descriptionBox!.width).toBeGreaterThan(amountBox!.width * 1.7);
    await page.screenshot({ path: 'tmp/repair-intake-mobile.png', fullPage: true });
});


test('next explains missing fields and focuses them on mobile', async ({ page }) => {
    await page.goto('/consulta');
    await page.locator('input[name=password]').fill(process.env.REPAIR_TECH_PASSWORD ?? 'Reypablo');
    await page.getByRole('button', { name: 'Ingresar', exact: true }).click();
    await page.goto('/ingreso');
    const next = page.getByRole('button', { name: 'Siguiente', exact: true });
    await expect(next).toBeEnabled();
    await next.tap();
    const customer = page.getByLabel(/Nombre del cliente/);
    await expect(customer).toBeFocused();
    await expect(customer).toHaveAttribute('aria-invalid', 'true');
    await expect(page.locator('#intake-validation')).toContainText('Nombre del cliente');
    await customer.fill('Prueba de validacion sin guardar');
    await expect(page.locator('#intake-validation')).toHaveCount(0);
    await next.tap();
    await page.locator('select').filter({ has: page.locator('option', { hasText: 'Celulares' }) }).selectOption('1');
    await next.tap();
    const brand = page.getByRole('combobox', { name: 'Marca', exact: true });
    await expect(brand).toBeFocused();
    await expect(page.locator('#intake-validation')).toContainText('marca');
    await brand.tap();
    await page.getByRole('option', { name: 'SAMSUNG', exact: true }).tap();
    await next.tap();
    await expect(page.getByPlaceholder('Ej: Samsung A54')).toBeFocused();
    await page.getByPlaceholder('Ej: Samsung A54').fill('Samsung A54');
    await next.tap();
    const description = page.getByRole('textbox', { name: 'Detalle de la falla', exact: true });
    const services = page.getByRole('combobox', { name: 'Elegir falla o servicio', exact: true });
    await expect(services).toBeFocused();
    await services.selectOption({ label: 'Otro servicio' });
    await expect(description).toHaveValue('');
    await description.fill('Pantalla rota');
    await next.tap();
    const amount = page.getByRole('textbox', { name: 'Monto', exact: true });
    await expect(amount).toBeFocused();
    await expect(page.locator('#intake-validation')).toContainText('monto o A presupuestar');
    await page.getByRole('button', { name: 'A presupuestar', exact: true }).tap();
    await next.tap();
    await expect(page.getByRole('heading', { name: 'Entrega, fotos y repuesto' })).toBeVisible();
    await expect(page.locator('#intake-validation')).toHaveCount(0);
});
